export type ViewKey = 'view' | 'layout' | 'continuous' | 'continuousHint' | 'pages' | 'pagesHint' | 'page' | typeof outlineKeys[number];
const keys: ViewKey[] = ['view', 'layout', 'continuous', 'continuousHint', 'pages', 'pagesHint', 'page', ...outlineKeys];
